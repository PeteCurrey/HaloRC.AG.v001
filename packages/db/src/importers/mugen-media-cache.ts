/**
 * Resolve media status for any MUGEN product following strict rules:
 * 1. Exact MUGEN part number match
 * 2. Exact MUGEN product page match
 * If no verified official image is present: return IMAGE_NOT_FOUND and MEDIA_REVIEW_REQUIRED.
 * Never substitute third-party, Google, or competitor images.
 */
export function resolveMugenProductMedia(
  sku: string,
  title: string,
  productType: string
): MugenMediaRecord {
  const normalizedSku = sku.trim().toUpperCase()
  const cached = VERIFIED_MUGEN_MEDIA_CACHE[normalizedSku]

  if (cached && cached.imageUrl) {
    return {
      id: `med-mugen-${normalizedSku}`,
      mugenSku: normalizedSku,
      productName: title,
      productType,
      productUrl: cached.productUrl ?? null,
      imageUrl: cached.imageUrl ?? null,
      sourceUrl: cached.sourceUrl ?? null,
      sourceDomain: cached.sourceDomain ?? 'www.mugenshop.eu',
      sourcePageUrl: cached.sourcePageUrl ?? null,
      retrievalTimestamp: new Date().toISOString(),
      mediaConfidence: 'EXACT_SKU_MATCH',
      matchingMethod: 'EXACT_MUGEN_PRODUCT_PAGE',
      reviewCategory: 'IMAGE_MATCHED',
      rightsReviewStatus: 'RIGHTS_REVIEW_REQUIRED',
      reviewNotes: cached.reviewNotes ?? 'Matched from official Mugen Seiki web resource.',
      createdAt: '2026-09-17T12:00:00Z',
      updatedAt: new Date().toISOString(),
    }
  }

  // Exact match not verified: DO NOT attach image
  return {
    id: `med-mugen-${normalizedSku}`,
    mugenSku: normalizedSku,
    productName: title,
    productType,
    productUrl: `https://www.mugenshop.eu/search?search=${encodeURIComponent(normalizedSku)}`,
    imageUrl: null,
    sourceUrl: null,
    sourceDomain: 'www.mugenshop.eu',
    sourcePageUrl: null,
    retrievalTimestamp: null,
    mediaConfidence: 'UNMATCHED',
    matchingMethod: 'NONE',
    reviewCategory: 'IMAGE_NOT_FOUND',
    rightsReviewStatus: 'RIGHTS_REVIEW_REQUIRED',
    reviewNotes: 'No verified official high-resolution image automatically matched. Requires manual admin media review.',
    createdAt: '2026-09-17T12:00:00Z',
    updatedAt: new Date().toISOString(),
  }
}
